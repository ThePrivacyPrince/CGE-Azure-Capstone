#!/usr/bin/env python3
"""Generate FAFO's System Security Plan as OSCAL 1.1.2 JSON (oscal/ssp.json).

Federal track: the SSP "goes out as OSCAL". Its content is not written by hand into JSON;
it is generated from frameworks/ssp-implementation.json (components and, per NIST SP 800-53
Rev. 5 control, how each component implements it). A change to the plan is therefore a
reviewed diff to that file, and tests/test_oscal.py fails CI if oscal/ssp.json is stale,
schema-invalid, or claims a control outside FAFO's tailored Moderate baseline.

    python3 scripts/generate_ssp.py            # rewrite oscal/ssp.json
    python3 scripts/generate_ssp.py --check    # exit 1 if oscal/ssp.json is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "frameworks" / "ssp-implementation.json"
OUT = ROOT / "oscal" / "ssp.json"
OSCAL_VERSION = "1.1.2"
# One namespace for every deterministic FAFO OSCAL UUID (profile, SSP, POA&M).
NAMESPACE = uuid.UUID("6f1c3a52-6a4e-4b4c-9c4d-fa50fa50fa50")
FAFO_NS = "https://fafo.example/ns/oscal"
SP800_60 = "https://doi.org/10.6028/NIST.SP.800-60v2r1"


def oscal_control_id(label: str) -> str:
    """AC-6(5) -> ac-6.5 (OSCAL catalog ids)."""
    base, _, enh = label.partition("(")
    return base.lower() + (f".{enh.rstrip(')')}" if enh else "")


def uid(*parts: str) -> str:
    return str(uuid.uuid5(NAMESPACE, ":".join(parts)))


def build_ssp(source: dict[str, Any], last_modified: str) -> dict[str, Any]:
    system = source["system"]
    comp_uuid = {c["key"]: uid("component", c["key"]) for c in source["components"]}
    level = system["sensitivity"]
    impact = {"base": level}
    return {
        "system-security-plan": {
            "uuid": uid("ssp", system["shortName"]),
            "metadata": {
                "title": f"{system['name']} System Security Plan",
                "last-modified": last_modified,
                "version": "1.0.0",
                "oscal-version": OSCAL_VERSION,
                "roles": [
                    {"id": "system-owner", "title": "System Owner"},
                    {"id": "grc-engineer", "title": "GRC Engineer"},
                ],
                "parties": [{"uuid": uid("party", "fafo"), "type": "organization", "name": "FAFO Inc."}],
                "responsible-parties": [
                    {"role-id": "system-owner", "party-uuids": [uid("party", "fafo")]},
                ],
                "remarks": "Generated by scripts/generate_ssp.py from frameworks/ssp-implementation.json. Do not edit by hand.",
            },
            "import-profile": {"href": "fafo-moderate-profile.json"},
            "system-characteristics": {
                "system-ids": [{"identifier-type": "https://ietf.org/rfc/rfc4122", "id": uid("system", system["shortName"])}],
                "system-name": system["name"],
                "system-name-short": system["shortName"],
                "description": system["description"],
                "security-sensitivity-level": level,
                "system-information": {
                    "information-types": [
                        {
                            "uuid": uid("information-type", "compliance-evidence"),
                            "title": "Compliance and audit evidence",
                            "description": "Control-test results, role-assignment snapshots, run manifests and reports about FAFO's Azure estate.",
                            "categorizations": [{"system": SP800_60, "information-type-ids": ["C.3.5.8"]}],
                            "confidentiality-impact": impact,
                            "integrity-impact": impact,
                            "availability-impact": {"base": "fips-199-low"},
                        }
                    ]
                },
                "security-impact-level": {
                    "security-objective-confidentiality": level,
                    "security-objective-integrity": level,
                    "security-objective-availability": "fips-199-low",
                },
                "status": {"state": "operational"},
                "authorization-boundary": {"description": system["boundary"]},
            },
            "system-implementation": {
                "users": [
                    {
                        "uuid": uid("user", "grc-engineer"),
                        "title": "GRC engineer (human operator)",
                        "role-ids": ["grc-engineer"],
                        "remarks": "Applies Terraform from a reviewed, saved plan; approves remediation in PRs.",
                    }
                ],
                "components": [
                    {
                        "uuid": comp_uuid[c["key"]],
                        "type": c["type"],
                        "title": c["title"],
                        "description": c["description"],
                        "props": [{"name": "implementation-path", "ns": FAFO_NS, "value": c["path"]}],
                        "status": {"state": "operational"},
                    }
                    for c in source["components"]
                ],
            },
            "control-implementation": {
                "description": "How FAFO's GRC pipeline implements its tailored NIST SP 800-53 Rev. 5 Moderate baseline. Every statement names the component, and the component names the code that does it.",
                "implemented-requirements": [
                    {
                        "uuid": uid("implemented-requirement", label),
                        "control-id": oscal_control_id(label),
                        "by-components": [
                            {
                                "component-uuid": comp_uuid[s["component"]],
                                "uuid": uid("by-component", label, s["component"]),
                                "description": s["statement"],
                            }
                            for s in statements
                        ],
                    }
                    for label, statements in sorted(source["implementedRequirements"].items(), key=lambda kv: oscal_control_id(kv[0]))
                ],
            },
        }
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if oscal/ssp.json is out of date")
    args = parser.parse_args()
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    current = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else None
    if args.check:
        if current is None:
            print(f"{OUT} missing", file=sys.stderr)
            return 1
        expected = build_ssp(source, current["system-security-plan"]["metadata"]["last-modified"])
        if expected != current:
            print(f"{OUT} is out of date: run python3 scripts/generate_ssp.py", file=sys.stderr)
            return 1
        print("oscal/ssp.json is current")
        return 0
    stamp = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    ssp = build_ssp(source, stamp)
    if current is not None and build_ssp(source, current["system-security-plan"]["metadata"]["last-modified"]) == current:
        print("oscal/ssp.json already current; unchanged")
        return 0
    OUT.write_text(json.dumps(ssp, indent=2) + "\n", encoding="utf-8")
    n = len(ssp["system-security-plan"]["control-implementation"]["implemented-requirements"])
    print(f"wrote {OUT} ({n} implemented requirements)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
